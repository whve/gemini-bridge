"""Deterministic Local Simulation Backend (`mock`) for offline CI/unit/integration testing.

NOTE: This backend is strictly for local automated testing (`--backend mock`) when testing
CLI lifecycle, background workers, SQLite state persistence, and MCP server calls without
incurring paid API costs or requiring an interactive browser login. It explicitly labels all
generated outputs as `[MOCK SIMULATION - NOT A LIVE GEMINI EXECUTION]`.
"""

from __future__ import annotations

import time
from typing import Any, Callable, Dict, Optional

from ..storage import extract_sources_from_markdown
from ..tasks import DetectionState, TaskMode, TaskRecord, TaskStatus
from .base import BackendResult, TaskBackend


class MockSimulationBackend(TaskBackend):
    """Deterministic simulation backend for local pipeline verification."""

    name = "mock"

    def __init__(self, delay_seconds: float = 0.2):
        self.delay_seconds = delay_seconds

    def check_health(self) -> Dict[str, Any]:
        return {
            "backend": self.name,
            "ready": True,
            "reason": "Deterministic local simulation backend ready (for unit/integration tests only).",
        }

    def execute_task(
        self,
        task: TaskRecord,
        on_progress: Optional[Callable[[str, Dict[str, Any]], None]] = None,
    ) -> BackendResult:
        if on_progress:
            on_progress("submitted", {"backend": "mock", "task_id": task.task_id})
        time.sleep(self.delay_seconds)

        # Support test triggers in prompt for testing failure/needs_user_action/timeout paths
        if "[TRIGGER_NEEDS_LOGIN]" in task.prompt:
            return BackendResult(
                status=TaskStatus.NEEDS_USER_ACTION,
                detection_state=DetectionState.VERIFIED,
                external_url="https://gemini.google.com/app",
                error_message="Simulated login required.",
                user_action_hint="Log in to Gemini web app and run `gemini-bridge resume`.",
            )
        if "[TRIGGER_DOM_ERROR]" in task.prompt:
            return BackendResult(
                status=TaskStatus.FAILED,
                detection_state=DetectionState.DOM_CHANGED_OR_UNPARSEABLE,
                external_url="https://gemini.google.com/app",
                error_message="Simulated DOM selector mismatch.",
            )

        if task.mode == TaskMode.APP_TASK.value and "[ALLOW_MOCK_APP_TASK]" not in task.prompt:
            return BackendResult(
                status=TaskStatus.NEEDS_USER_ACTION,
                detection_state=DetectionState.VERIFIED,
                external_url="https://gemini.google.com/app",
                error_message=(
                    "Gemini App Tasks have no public API and require an authenticated personal Google AI Pro/Ultra web session."
                ),
                user_action_hint=(
                    "Switch to an authenticated personal Google account on https://gemini.google.com/app "
                    "with 'Task' mode enabled (see https://support.google.com/gemini/answer/17094507)."
                ),
            )

        return self._build_simulated_report(task)

    def poll_or_fetch(
        self,
        task: TaskRecord,
        on_progress: Optional[Callable[[str, Dict[str, Any]], None]] = None,
    ) -> BackendResult:
        time.sleep(self.delay_seconds / 2.0)
        return self._build_simulated_report(task)

    def _build_simulated_report(self, task: TaskRecord) -> BackendResult:
        report_md = (
            f"# [LOCAL TEST SIMULATION] Report for `{task.task_id}`\n\n"
            f"> **Notice**: This file was generated by the `mock` test backend for local pipeline verification.\n\n"
            f"## Submitted Prompt\n\n"
            f"{task.prompt}\n\n"
            f"## Verified Architecture References\n\n"
            f"- [Gemini Deep Research API Documentation](https://ai.google.dev/gemini-api/docs/deep-research)\n"
            f"- [Manage your tasks & workflows in Gemini Apps](https://support.google.com/gemini/answer/17094507)\n"
            f"- [Schedule actions in Gemini Apps](https://support.google.com/gemini/answer/16316416)\n"
            f"- [Antigravity Agent Documentation](https://ai.google.dev/gemini-api/docs/antigravity-agent)\n"
        )
        sources = extract_sources_from_markdown(report_md)
        return BackendResult(
            status=TaskStatus.COMPLETED,
            detection_state=DetectionState.VERIFIED,
            report_markdown=report_md,
            sources=sources,
            external_id=f"mock-{task.task_id}",
            external_url=f"https://gemini.google.com/app/mock/{task.task_id}",
        )
